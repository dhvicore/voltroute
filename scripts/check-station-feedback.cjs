const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require('typescript');
const Database = require('better-sqlite3');
const db = new Database(':memory:');
db.exec(`CREATE TABLE users(id TEXT PRIMARY KEY,name TEXT); CREATE TABLE stations(id TEXT PRIMARY KEY,rating REAL,rating_count INTEGER,updated_at TEXT); CREATE TABLE reviews(id TEXT PRIMARY KEY,user_id TEXT,station_id TEXT,rating INTEGER,comment TEXT,created_at TEXT DEFAULT (datetime('now'))); CREATE TABLE notifications(id TEXT PRIMARY KEY); INSERT INTO users VALUES('driver','Test Driver'); INSERT INTO stations VALUES('station',0,0,NULL);`);
let unauthorized = false;
const api = {};
const source = fs.readFileSync('app/api/reviews/route.ts','utf8');
const code = ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
vm.runInNewContext(code,{exports:api,URL,console,require(name){
  if(name==='@/lib/db') return {getDb:()=>db};
  if(name==='@/lib/init') return {ensureInit(){}};
  if(name==='@/lib/auth') return {requireAuth(){if(unauthorized)throw Error('Unauthorized'); return {userId:'driver'}}};
  if(name.includes('notify')) throw Error('Feedback must not send provider notifications');
  return require(name);
}});
const req = body=>({json:async()=>body});
(async()=>{
  const body={station_id:'station',rating:4,comment:'  Easy to access and charge.  '};
  assert.equal((await api.POST(req(body))).status,201);
  let review=db.prepare('SELECT * FROM reviews').get();
  assert.equal(review.comment,'Easy to access and charge.');
  assert.equal(db.prepare("SELECT rating FROM stations WHERE id='station'").get().rating,4);
  assert.equal((await api.POST(req({...body,rating:5,comment:'Updated feedback'}))).status,200);
  assert.equal(db.prepare('SELECT COUNT(*) count FROM reviews').get().count,1,'editing must not duplicate feedback');
  assert.equal(db.prepare("SELECT rating FROM stations WHERE id='station'").get().rating,5);
  for(const rating of [0,6,1.5,'5',null]) assert.equal((await api.POST(req({...body,rating}))).status,400);
  for(const comment of [123,{},'a'.repeat(1501)]) assert.equal((await api.POST(req({...body,comment}))).status,400);
  assert.equal((await api.POST(req(null))).status,400);
  assert.equal((await api.POST({json:async()=>{throw Error('malformed')}})).status,400);
  assert.equal((await api.POST(req({...body,station_id:'missing'}))).status,404);
  unauthorized=true;
  assert.equal((await api.POST(req(body))).status,401);
  const result=await (await api.GET({url:'http://localhost/api/reviews?station_id=station'})).json();
  assert.equal(result.reviews[0].comment,'Updated feedback');
  assert.equal(result.summary.count,1);
  assert.equal(result.summary.rating,5);
  assert.equal((await api.GET({url:'http://localhost/api/reviews'})).status,400);
  assert.equal(db.prepare('SELECT COUNT(*) count FROM notifications').get().count,0,'no station provider notifications');
  console.log('PASS: feedback persistence, editing, rating aggregates, validation, authentication, listing, and no provider notifications');
})().catch(e=>{console.error(e);process.exitCode=1}).finally(()=>db.close());
