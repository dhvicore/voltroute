const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const Database = require('better-sqlite3');
const db = new Database(':memory:');
let userId = 'driver';
let role = 'user';
const messages = [];
function load(file) {
  const module = { exports: {} };
  const code = ts.transpileModule(fs.readFileSync(file,'utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
  vm.runInNewContext(code, {exports:module.exports,require(name){
    if(name==='@/lib/booking-slot') return load('lib/booking-slot.ts');
    if(name==='@/lib/booking-cost') return load('lib/booking-cost.ts');
    if(name==='@/lib/db') return {getDb:()=>db};
    if(name==='@/lib/auth') return {requireAuth:()=>({userId,role})};
    if(name==='@/lib/init') return {ensureInit(){}};
    if(name==='@/lib/notify') return {formatSlot:(d,t)=>`${d} ${t}`,notify:(...args)=>messages.push(args),notifyStation:(...args)=>messages.push(args)};
    if(name==='@/lib/planner-stations') return {managedStationIds:()=>role==='admin'?'all':[],isStationOperator:()=>false};
    if(name==='@/lib/sample-availability') return schedule;
    return require(name);
  },Date,URL,console});
  return module.exports;
}
const schedule = load('lib/sample-availability.ts');
db.exec(`
CREATE TABLE users(id TEXT PRIMARY KEY,name TEXT);
CREATE TABLE stations(id TEXT PRIMARY KEY,name TEXT,is_enabled INTEGER,chargers_estimated INTEGER,operator_verified INTEGER,live_source TEXT);
CREATE TABLE chargers(id TEXT PRIMARY KEY,station_id TEXT,status TEXT,power_kw REAL,price_per_kwh REAL,session_fee REAL,connector_type TEXT,charging_type TEXT);
CREATE TABLE bookings(id TEXT PRIMARY KEY,user_id TEXT,station_id TEXT,charger_id TEXT,vehicle_id TEXT,booking_date TEXT,start_time TEXT,end_time TEXT,duration_minutes INTEGER,estimated_cost REAL,deposit_amount REAL,payment_status TEXT DEFAULT 'unpaid',payment_method TEXT,payment_ref TEXT,operator_status TEXT DEFAULT 'pending',status TEXT DEFAULT 'confirmed',updated_at TEXT);
INSERT INTO users VALUES('driver','Test Driver');
INSERT INTO stations VALUES('sample','Sample Station',1,1,0,NULL);
INSERT INTO chargers VALUES('charger-a','sample','available',50,18,0,'CCS2','DC');
INSERT INTO bookings(id,user_id,station_id,charger_id,booking_date,start_time,end_time,duration_minutes,estimated_cost,deposit_amount) VALUES('request','driver','sample','charger-a','2099-10-23','08:00','08:30',30,450,450);
`);
const pay = load('app/api/bookings/[id]/pay/route.ts').POST;
const review = load('app/api/operator/bookings/[id]/route.ts').POST;
const availability = load('app/api/chargers/[id]/availability/route.ts').GET;
const create = load('app/api/bookings/route.ts').POST;
const request = body=>({json:async()=>body});
const params = {params:{id:'request'}};
(async()=>{
  assert.equal((await pay(request({method:'upi'}),params)).status,409,'pending online payment rejected');
  assert.equal((await pay(request({method:'cash'}),params)).status,409,'pending cash selection rejected');
  assert.equal(messages.length,0,'pending payment causes no notifications');
  role='admin';
  assert.equal((await review(request({action:'accept'}),params)).status,200);
  assert.match(messages[0][3],/cash at the station/,'acceptance notification explains optional payment');
  assert.equal((await review(request({action:'accept'}),params)).status,409,'duplicate acceptance rejected');
  role='user';
  assert.equal((await pay(request({method:'cash'}),params)).status,200);
  let saved=db.prepare("SELECT * FROM bookings WHERE id='request'").get();
  assert.equal(saved.payment_status,'unpaid','cash selection must not mark booking paid');
  assert.equal(saved.payment_method,'cash');
  assert.equal(saved.payment_ref,null,'cash has no payment receipt');
  assert.equal((await pay(request({method:'card'}),params)).status,200,'may switch cash to demo online later');
  assert.equal(db.prepare("SELECT payment_status FROM bookings WHERE id='request'").get().payment_status,'paid');
  assert.equal((await pay(request({method:'upi'}),params)).status,409,'duplicate charge rejected');
  userId='other';
  assert.equal((await pay(request({method:'cash'}),params)).status,404,'ownership enforced');
  userId='driver';
  db.prepare("UPDATE bookings SET payment_status='unpaid',status='cancelled' WHERE id='request'").run();
  assert.equal((await pay(request({method:'upi'}),params)).status,409,'cancelled booking rejected');
  const date='2099-10-24';
  const slots=(await (await availability({url:`http://localhost/api?date=${date}`},{params:{id:'charger-a'}})).json());
  assert.equal(slots.sample_schedule,true);
  assert.equal(slots.booked_slots.length,3);
  const first=slots.booked_slots[0];
  const blocked=await create(request({station_id:'sample',charger_id:'charger-a',booking_date:date,start_time:first.start_time,duration_minutes:30}));
  assert.equal(blocked.status,409,'sample unavailable slot blocked by booking API too');
  const booked=await create(request({station_id:'sample',charger_id:'charger-a',booking_date:date,start_time:'08:00',duration_minutes:30}));
  assert.equal(booked.status,201,'available sample slot bookable');
  assert.match(messages.at(-1)[3],/No payment is needed/);
  db.prepare("UPDATE stations SET operator_verified=1 WHERE id='sample'").run();
  const verified=await (await availability({url:`http://localhost/api?date=${date}`},{params:{id:'charger-a'}})).json();
  assert.equal(verified.sample_schedule,false,'provider station excludes synthetic occupancy');
  assert.equal(verified.booked_slots.length,1,'actual bookings still shown');
  const counts=new Set(Array.from({length:13},(_,i)=>{
    const t=`${String(i+8).padStart(2,'0')}:00`;
    return ['charger-a','charger-b'].filter(id=>!schedule.sampleBusySlots(id,date).some(s=>s.start_time<=t&&s.end_time>t)).length;
  }));
  assert.ok(counts.size>1,'sample free counts vary by time and charger');
  console.log('PASS: acceptance gating, notification timing, optional cash, deferred online payment, ownership, duplicate protection, sample variation and matching booking conflicts');
})().catch(e=>{console.error(e);process.exitCode=1}).finally(()=>db.close());
