const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const output = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('lib/charging-plan.ts','utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText, {exports:output});
const {planChargingStops,ChargingPlanError} = output;
const car={id:'curvv',name:'Tata Curvv EV',batteryKwh:55,rangeKm:400,maxDcKw:70,maxAcKw:7.2,connector:'CCS2'};
const input={source:'Mumbai',destination:'Pune',battery:43,connector:'CCS2',preference:'fastest'};
function station(id,km,power=60,connector='CCS2',detour=1){return {id,name:id,available:1,detourMinutes:detour,distanceAlongRoute:km,chargers:[{id:`${id}-charger`,connector,power,price:16,sessionFee:0,available:true}]};}
const dc=station('dc',114);
let plan=planChargingStops(input,147,[dc],car);
assert.equal(plan.stops.length,1);
assert.equal(plan.stops[0].targetBattery,24,'charge only enough to arrive with reserve');
assert.ok(plan.chargeMinutes>=10 && plan.chargeMinutes<=20,'DC top-up should take minutes, not hours');
assert.ok(plan.arrivalBattery>=15);
assert.equal(plan.detourMinutes,1);
plan=planChargingStops({...input,connector:'Type 2'},147,[station('ac',114,22,'Type 2')],car);
assert.ok(plan.chargeMinutes<=60,'AC trip top-up must not unnecessarily fill to 80%');
assert.ok(plan.chargeMinutes>=45,'respect the car AC limit, do not invent a fast charge');
plan=planChargingStops({...input,battery:62},147,[dc],car);
assert.equal(plan.chargeMinutes,0,'skip charging entirely when range is sufficient');
assert.equal(plan.stops.length,0);
plan=planChargingStops(input,147,[station('fast',80,70),station('slow',114,7)],car);
assert.equal(plan.stops[0].stationId,'fast','prefer faster compatible charging over simply the furthest station');
const lowLimit={...car,maxDcKw:7};
const limited=planChargingStops(input,147,[dc],lowLimit);
assert.ok(limited.chargeMinutes>=50,'power is capped by the car charging limit');
assert.throws(()=>planChargingStops({...input,battery:5},147,[dc],car),ChargingPlanError,'never invent reachable charge at an unreachable station');
assert.throws(()=>planChargingStops(input,147,[],car),ChargingPlanError,'no stations produces a clear route warning');
plan=planChargingStops({...input,battery:90,bookedStops:[{stationId:'dc',chargerId:'dc-charger',minutes:30}]},147,[dc],car);
assert.equal(plan.stops[0].booked,true);
assert.equal(plan.chargeMinutes,30,'respect a driver-booked session duration');
assert.throws(()=>planChargingStops({...input,bookedStops:[{stationId:'dc',chargerId:'missing',minutes:30}]},147,[dc],car),ChargingPlanError);
const acCar={...car,batteryKwh:17.3,rangeKm:170,maxDcKw:0,maxAcKw:3.3,connector:'Type 2'};
plan=planChargingStops({...input,connector:'Type 2',battery:43},147,[station('ac-only',50,22,'Type 2')],acCar);
assert.ok(plan.chargeMinutes>120,'a genuinely slow AC-only car still needs a long charge; never hide it');
plan=planChargingStops({...input,battery:50},600,[station('s1',100),station('s2',330),station('s3',500)],car);
assert.ok(plan.stops.length>=2,'long routes retain multiple necessary charging stops');
assert.ok(plan.arrivalBattery>=15);
console.log('PASS: 147 km DC/AC timing, minimum top-up, adequate-battery no-stop plan, faster charger selection, car limits, impossible routes, fixed bookings, AC-only honesty, and multi-stop journeys');
